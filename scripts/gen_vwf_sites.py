#!/usr/bin/env python3
"""Writes game/src/version/kabuto/menu_vwf_sites.asm: call sites in the original Kabuto
ROM that are redirected to the centred-name VWF routines (game/src/patch/menu_vwf.asm).
Every site is checked against baserom_kabuto.gbc."""
r=open('baserom_kabuto.gbc','rb').read()
OFFSET="7A:41FA 7A:426E 7A:42CC 7A:4305 54:4B6C 54:5816 54:582B 11:68E3 11:68F8 04:6D70 06:704A 07:5418".split()
CENTERED="7A:4204 7A:4276 7A:42D3 7A:430D 54:4B7B 54:5823 54:5838 11:68F0 11:6905 F8:62F3 F8:6315 F8:6337 F9:4360 F9:4379 04:6D7A 06:7054 07:5428".split()
LEFT="7A:45D7 7A:4659 54:6540 54:663D 54:6A92 FA:67BA".split()
out=['; Kabuto call sites that draw names into fixed cells, redirected to the VWF routines',
'; in patch/menu_vwf.asm. Generated by scripts/gen_vwf_sites.py, each site checked against',
'; baserom_kabuto.gbc: calls (or jumps) to $290E (centring offset) and $28E0 (draw string).','',
'INCLUDE "game/src/common/constants.asm"','INCLUDE "game/src/common/macros.asm"','']
def emit(sites,target,tail,opcodes,kind):
    for s in sites:
        b,a=s.split(':'); b=int(b,16); a=int(a,16)
        o=b*0x4000+a-0x4000
        op=r[o:o+3]
        assert op[1:]==tail and op[0] in opcodes,(s,op.hex())
        ins='call' if op[0]==0xCD else 'jp'
        out.extend([f'SECTION "VWF {kind} {b:02X}_{a:04X}", ROMX[${a:04X}], BANK[${b:02X}]',f'  {ins} {target}',''])
emit(OFFSET,'PutStringVWFOffset',bytes([0x0E,0x29]),(0xCD,),'Offset')
emit(CENTERED,'PutStringVWFCentered',bytes([0xE0,0x28]),(0xCD,0xC3),'Name')
emit(LEFT,'PutStringVWFLeft',bytes([0xE0,0x28]),(0xCD,0xC3),'Left')
open('game/src/version/kabuto/menu_vwf_sites.asm','w',encoding='utf-8').write('\n'.join(out))
print(len(OFFSET),len(CENTERED),len(LEFT),'sites ok')
