#!/usr/bin/env python3
"""Writes game/src/version/kabuto/vs_names.asm: Latin names for the opponent name table of the
vs screen (bank 7A, pointer table at $4DF2, kana coded in the original). The first byte of each
entry (not a character) is kept from the original ROM."""
NAMES="""Arika Karin Kouji Masashi Yuuko Kikuhime Iwanoi Kagamiyama Kurouma Dai Hiroshi Rumi Matsu Ayaka Kimie Shimeta Hachirou Kage Rintarou Takenaka Shiratama Nae Imogorilla Select-mies Mitsugu Retortrouva Robo-jengi Moritama Medatohtori Senju Nayuta""".split()
r=open('baserom_kabuto.gbc','rb').read()
def off(a): return 0x7A*0x4000+a-0x4000
tbl=off(0x4DF2)
out=['; Opponent names of the vs screen (bank 7A). Generated by scripts/gen_vs_names.py.','',
'SECTION "Vs Screen Name Pointers", ROMX[$4DF2], BANK[$7A]']
data=['SECTION "Vs Screen Names", ROMX[$7900], BANK[$7A]']
addr=0x7900
ptrs=[]
for i,n in enumerate(NAMES):
    p=r[tbl+2*i]|r[tbl+2*i+1]<<8
    b0=r[off(p)]
    assert len(n)<=11
    ptrs.append(f'  dw VsName{i:02d}')
    data.append(f'VsName{i:02d}:\n  db ${b0:02X}, "{n}", $CB')
out+=ptrs+['']+data
open('game/src/version/kabuto/vs_names.asm','w',encoding='utf-8').write('\n'.join(out)+'\n')
print(len(NAMES),'names')
