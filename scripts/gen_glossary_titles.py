#!/usr/bin/env python3
"""Mr Kitama's glossary list ("Meda terms", bank 07): Finnish titles -> game/src/version/kabuto/glossary_titles.asm.

The game keeps 128 title pointers at 07:7A3E (58 used) and the titles from 07:7B3E on. Every title is a prefix byte
(icon of the group, 00 = none) followed by the text and $CB. The list code skips the prefix and draws the text into 7 cells
(PutStringFixedLength -> menu VWF). Edit scripts/res/glossary_titles.csv (index;prefix;original;finnish) and run this script.
The bullet of the sub items is written as '•' (VWF code $1C). Titles longer than ~9 letters are drawn with the narrow font."""
import csv,os,sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..'))
sys.path.insert(0,'scripts')
from common import utils, tilesets
cm=utils.reverse_dict(tilesets.get_tileset('VWF',override_offset=0x0)); cm[' ']=0x20
src=open('game/src/patch/vwf.asm',encoding='utf-8').read()
def tab(name):
    blk=src.split(name+'::')[1]
    rows=__import__('re').findall(r'^\s*db ([0-9, ]+) ;',blk,__import__('re').M)[:16]
    return [int(x) for r in rows for x in r.split(',')]
wide,narrow=tab('VWFDrawLetterTable'),tab('VWFDrawNarrowLetterTable')
rows=[r for r in csv.reader(open('scripts/res/glossary_titles.csv',encoding='utf-8'),delimiter=';') if r and not r[0].startswith('#')]
BASE=0x7B3E; LIMIT=0x8000; N=128
out=['; Generated by scripts/gen_glossary_titles.py from scripts/res/glossary_titles.csv, do not edit.','',
     'SECTION "Glossary Title Pointers", ROMX[$7A3E], BANK[$07]','GlossaryTitlePointers::']
data=[]; addr=BASE; ptrs=[]
for r in rows:
    idx,pre,orig,fi=int(r[0]),int(r[1],16),r[2],r[3]
    assert idx==len(ptrs),(idx,len(ptrs))
    codes=[]
    for c in fi:
        if c=='•': codes.append(0x1C)
        elif c in cm: codes.append(cm[c])
        else: sys.exit('no VWF code for %r in %r'%(c,fi))
    w=sum(wide[c]+1 for c in codes); n=sum(narrow[c]+1 for c in codes)
    if n>7*8+1: print('TOO WIDE',idx,fi,n,'>',57); sys.exit(1)
    if w>7*8+1: print('narrow font: %d %s (%d px)'%(idx,fi,w))
    ptrs.append(addr); data.append((idx,pre,codes,fi)); addr+=len(codes)+2
empty=addr; addr+=2
assert addr<=LIMIT,'out of space: $%X'%addr
for i in range(N): out.append('  dw $%04X%s'%(ptrs[i] if i<len(ptrs) else empty,' ; %d %s'%(i,data[i][3]) if i<len(ptrs) else ''))
out+=['','SECTION "Glossary Title Text", ROMX[$%04X], BANK[$07]'%BASE]
for idx,pre,codes,fi in data: out.append('  db $%02X, %s$CB ; %d %s'%(pre,''.join('$%02X, '%c for c in codes),idx,fi))
out.append('  db $00, $CB ; empty')
open('game/src/version/kabuto/glossary_titles.asm','w',encoding='utf-8',newline='\n').write('\n'.join(out)+'\n')
print('ok %d titles, text ends at $%04X'%(len(data),addr))
